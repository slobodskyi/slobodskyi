import { isPublished } from '../schema.ts';
import type { ContentSource } from '../source.ts';
import { loadRecords, type Problem } from './load.ts';

export interface RedirectRule {
  from: string;
  to: string;
  status: 301 | 302 | 307 | 308;
  /** Where the rule came from: a record address or a static list file. */
  origin: string;
}

export interface RedirectsResult {
  ok: boolean;
  rules: RedirectRule[];
  /** Contents of the Cloudflare `_redirects` file. */
  file: string;
  problems: Problem[];
}

/** Cloudflare Workers static assets limit for static (non-splat) redirect rules. */
const STATIC_RULE_LIMIT = 2000;

/** Parses a static redirect list: CSV with header `from,to,status` (status optional, default 301). */
export function parseRedirectsCsv(
  text: string,
  origin: string,
): { rules: RedirectRule[]; problems: Problem[] } {
  const rules: RedirectRule[] = [];
  const problems: Problem[] = [];
  const lines = text.split(/\r?\n/).filter((l) => l.trim() && !l.trim().startsWith('#'));
  const [header, ...rows] = lines;
  if (!header || !/^from\s*,\s*to/i.test(header)) {
    if (lines.length)
      problems.push({ level: 'error', code: 'csv', message: `${origin}: header must be from,to,status` });
    return { rules, problems };
  }
  rows.forEach((row, i) => {
    const [from = '', to = '', status = '301'] = row.split(',').map((c) => c.trim());
    const code = Number(status);
    if (!from.startsWith('/') || !to || ![301, 302, 307, 308].includes(code)) {
      problems.push({ level: 'error', code: 'csv', message: `${origin}:${i + 2}: invalid row "${row}"` });
      return;
    }
    rules.push({ from, to, status: code as RedirectRule['status'], origin });
  });
  return { rules, problems };
}

/**
 * Generates `_redirects` from `legacyUrls` of published records plus static rules. Guarantees:
 * no rule shadows a live page, no conflicting duplicates, no chains (they are flattened to the
 * final target), no cycles.
 */
export async function buildRedirects(
  source: ContentSource,
  staticRules: RedirectRule[] = [],
): Promise<RedirectsResult> {
  const { records, problems } = await loadRecords(source);
  const live = new Set(records.filter((r) => isPublished(r.data)).map((r) => r.url));

  const candidates: RedirectRule[] = [...staticRules];
  for (const r of records) {
    if (!isPublished(r.data)) continue;
    for (const from of r.data.legacyUrls)
      candidates.push({ from, to: r.url, status: 301, origin: r.address });
  }

  const byFrom = new Map<string, RedirectRule>();
  for (const rule of candidates) {
    const err = (message: string) =>
      problems.push({ level: 'error', code: 'redirect', message: `${message} (${rule.origin})` });
    if (rule.from === rule.to) {
      err(`${rule.from} redirects to itself`);
      continue;
    }
    if (live.has(rule.from)) {
      err(`${rule.from} is a live page and cannot be redirected`);
      continue;
    }
    const existing = byFrom.get(rule.from);
    if (existing && existing.to !== rule.to) {
      err(`${rule.from} → ${rule.to} conflicts with → ${existing.to} (${existing.origin})`);
      continue;
    }
    if (!existing) byFrom.set(rule.from, rule);
  }

  // Flatten chains: a → b, b → c becomes a → c and b → c.
  const rules: RedirectRule[] = [];
  for (const rule of byFrom.values()) {
    let to = rule.to;
    const seen = new Set([rule.from]);
    let next = byFrom.get(to);
    while (next) {
      if (seen.has(to)) {
        problems.push({
          level: 'error',
          code: 'redirect',
          message: `redirect cycle through ${to} (${rule.origin})`,
        });
        break;
      }
      seen.add(to);
      to = next.to;
      next = byFrom.get(to);
    }
    if (to !== rule.to) {
      problems.push({
        level: 'warning',
        code: 'redirect-chain',
        message: `chain flattened: ${rule.from} → ${to}`,
      });
    }
    if (to.startsWith('/') && !live.has(to.replace(/[?#].*$/, ''))) {
      problems.push({
        level: 'warning',
        code: 'redirect-target',
        message: `${rule.from} → ${to}: target is not a live page`,
      });
    }
    rules.push({ ...rule, to });
  }

  rules.sort((a, b) => (a.from < b.from ? -1 : a.from > b.from ? 1 : 0));
  if (rules.length > STATIC_RULE_LIMIT) {
    problems.push({
      level: 'error',
      code: 'redirect-limit',
      message: `${rules.length} rules exceed ${STATIC_RULE_LIMIT}`,
    });
  }

  const file =
    '# Generated by `pnpm content redirects` from legacyUrls and data/redirects/. Do not edit.\n' +
    rules.map((r) => `${r.from} ${r.to} ${r.status}`).join('\n') +
    (rules.length ? '\n' : '');

  return { ok: !problems.some((p) => p.level === 'error'), rules, file, problems };
}
