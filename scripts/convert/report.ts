// Conversion report and parity checks against the live snapshot → data/convert-report.md.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { extractHeadings, extractInternalLinks, parseDocument } from '@slobodskyi/core';

interface Input {
  root: string;
  issues: { address: string; kind: string; detail: string }[];
  written: { address: string; url: string; status: string; legacyUrls: string[] }[];
  fixes: Record<string, { why: string }>;
  /** Sources of data/redirects/*.csv rules: live URLs removed on purpose. */
  staticRedirects: string[];
  snapshot: Map<
    string,
    {
      url: string;
      status: number;
      pageType: string;
      title: string;
      description: string;
      h1: string[];
      internalLinks: string[];
      anchors: { legacy: string; slugger: string }[];
    }
  >;
}

const PAGE_TYPES = new Set(['article', 'hub', 'category', 'page', 'home']);
/** Broken internal links accepted on purpose (none: the owner allows no exceptions). */
const KNOWN_BROKEN_LINKS = new Set<string>();

const fileOf = (root: string, address: string) => {
  const [path = '', lang = ''] = address.split(':');
  return join(root, 'content', path, `${lang}.mdx`);
};
const norm = (s: string | undefined) =>
  (s ?? '')
    .replace(/\u00a0/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

export function writeReport({ root, issues, written, snapshot, fixes, staticRedirects }: Input): void {
  const out: string[] = [];
  const published = written.filter((w) => w.status === 'published');
  const byUrl = new Map<string, string[]>();
  for (const w of published) byUrl.set(w.url, [...(byUrl.get(w.url) ?? []), w.address]);

  // 1. URL coverage.
  const live = [...snapshot.values()].filter((p) => p.status === 200 && PAGE_TYPES.has(p.pageType));
  // Live URLs listed in legacyUrls of a published record are redirected on purpose.
  const redirected = new Set([...published.flatMap((w) => w.legacyUrls), ...staticRedirects]);
  const missing = live
    .filter((p) => (byUrl.get(p.url)?.length ?? 0) === 0 && !redirected.has(p.url))
    .map((p) => p.url);
  const dupes = [...byUrl].filter(([, a]) => a.length > 1).map(([u, a]) => `${u}: ${a.join(', ')}`);
  const extra = published.filter((w) => !snapshot.has(w.url)).map((w) => `${w.url} (${w.address})`);

  // 2. SEO parity + anchors + links.
  const seo: string[] = [];
  const fixed: string[] = [];
  const anchors: string[] = [];
  const linkDiffs: string[] = [];
  const links = new Map<string, Set<string>>();
  const known = new Set([
    ...[...snapshot.values()].filter((p) => p.status === 200).map((p) => p.url),
    ...written.map((w) => w.url),
  ]);
  let legacyJsx = 0;
  for (const w of written) {
    const { data, body } = parseDocument(readFileSync(fileOf(root, w.address), 'utf8'));
    const fm = data as { title: string; seoTitle?: string; description?: string };
    const heads = extractHeadings(body);
    legacyJsx += heads.filter((h) => h.explicit).length;
    for (const l of extractInternalLinks(body)) {
      if (!known.has(l)) links.set(l, (links.get(l) ?? new Set()).add(w.address));
    }
    const page = snapshot.get(w.url);
    if (w.status !== 'published' || !page) continue;
    const diff: string[] = [];
    if (norm(fm.title) !== norm(page.h1[0])) diff.push(`H1: "${fm.title}" ≠ live "${page.h1[0] ?? ''}"`);
    if (norm(fm.seoTitle ?? fm.title) !== norm(page.title))
      diff.push(`title: "${fm.seoTitle ?? fm.title}" ≠ live "${page.title}"`);
    if (norm(fm.description) !== norm(page.description))
      diff.push(`description: "${fm.description ?? ''}" ≠ live "${page.description ?? ''}"`);
    const entry = `- \`${w.url}\` (${w.address})\n${diff.map((d) => `  - ${d}`).join('\n')}`;
    const why = fixes[w.url]?.why;
    if (why)
      fixed.push(`${entry}
  - why: ${why}`);
    else if (diff.length) seo.push(entry);
    const liveLinks = new Set(page.internalLinks);
    const notLive = extractInternalLinks(body).filter((l) => !liveLinks.has(l) && !KNOWN_BROKEN_LINKS.has(l));
    // Fixed pages may get new text (see the documented fixes); their links are not on the live page.
    if (notLive.length && !fixes[w.url])
      linkDiffs.push(`- \`${w.url}\`: ${notLive.map((l) => `\`${l}\``).join(', ')}`);
    const have = new Set(heads.map((h) => h.anchor));
    const lost = page.anchors.filter((a) => !have.has(a.legacy)).map((a) => `#${a.legacy}`);
    if (lost.length) anchors.push(`- \`${w.url}\`: ${lost.join(', ')}`);
  }

  const counts = (filter: (a: string) => boolean) => {
    const sel = written.filter((w) => filter(w.address));
    const pub = sel.filter((w) => w.status === 'published').length;
    return `${sel.length} files (${pub} published, ${sel.length - pub} draft)`;
  };

  out.push('# Conversion report (Step 4)', '', 'Generated by `pnpm convert`. Do not edit by hand.', '');
  out.push('## Records', '');
  for (const c of ['guides', 'hubs', 'categories', 'pages'])
    out.push(`- ${c}: ${counts((a) => a.startsWith(`${c}/`))}`);
  out.push(`- legacy H2 anchors kept as JSX headings: ${legacyJsx}`, '');

  out.push('## URL coverage', '');
  out.push(
    `Live 200 pages (article/hub/category/page/home): ${live.length}; mapped to exactly one published record: ${live.length - missing.length - dupes.length - live.filter((p) => redirected.has(p.url)).length}; redirected: ${live.filter((p) => redirected.has(p.url)).length}.`,
    '',
  );
  out.push(
    `- Live URLs without a record: ${missing.length ? missing.map((u) => `\`${u}\``).join(', ') : 'none'}`,
  );
  out.push(`- URLs with more than one record: ${dupes.length ? dupes.join('; ') : 'none'}`);
  out.push(`- Published records whose URL is not live: ${extra.length ? extra.join(', ') : 'none'}`, '');

  out.push('## SEO parity (title, description, H1 vs live snapshot)', '');
  out.push(seo.length ? seo.join('\n') : 'All match (apart from the documented fixes below).', '');
  out.push('### Documented legacy fixes (expected differences)', '');
  out.push(fixed.length ? fixed.join('\n') : 'None.', '');

  out.push('## Legacy anchors missing', '');
  out.push(
    anchors.length ? anchors.join('\n') : 'None: every anchor of the live site exists in the records.',
    '',
  );

  out.push('## Internal links to unknown pages', '');
  out.push(
    links.size
      ? [...links]
          .map(
            ([l, a]) =>
              `- \`${l}\`${KNOWN_BROKEN_LINKS.has(l) ? ' (known legacy 404, kept)' : ''} — ${[...a].join(', ')}`,
          )
          .join('\n')
      : 'None.',
    '',
  );

  out.push('## Internal links not found on the live page', '');
  out.push(
    linkDiffs.length
      ? linkDiffs.join('\n')
      : 'None: every internal link of a published record also exists on its live page.',
    '',
  );

  out.push('## Webflow fields not carried over', '');
  out.push(
    [
      '- articles: `card-title`, `card-description` (listing cards), `time-to-read` / `timerequired` (computable),',
      '  `group` / `proxy-category` (Adult/Other), `author` (single author), `webstory` (empty everywhere);',
      '  the FAQ JSON-LD generator script in `faq` (FAQ now lives in frontmatter `faq`).',
      '- hubs/categories: `category-description` / `dd` (card text), `order`, article counters, `link`.',
      '- rich text: table cell classes (`highlight`), embed `<style>` blocks, image alignment beyond `wide`.',
      '- service pages: layout, forms (newsletter, contacts), CMS lists, buttons; bodies are text extractions.',
    ].join('\n'),
    '',
  );

  out.push('## Not converted automatically', '');
  const kinds = new Map<string, typeof issues>();
  for (const i of issues) kinds.set(i.kind, [...(kinds.get(i.kind) ?? []), i]);
  if (!issues.length) out.push('Nothing.');
  for (const [kind, list] of [...kinds].sort()) {
    out.push(`### ${kind} (${list.length})`, '');
    for (const i of list) out.push(`- ${i.address}: ${i.detail}`);
    out.push('');
  }

  writeFileSync(join(root, 'data/convert-report.md'), out.join('\n').replace(/\n{3,}/g, '\n\n'));
  console.log(
    `convert: ${written.length} files, ${published.length} published; missing ${missing.length}, dupes ${dupes.length}, extra ${extra.length}, seo diffs ${seo.length}, fixes ${fixed.length}, anchors lost ${anchors.length}, link diffs ${linkDiffs.length}, issues ${issues.length}`,
  );
}
